// Curated career-changer destination occupations, keyed to real SOC 2020 unit groups.
//
// WHAT IS SOURCED (checked by scripts/ashe/validate.mjs):
// - soc: the 4-digit SOC 2020 unit group. Every code exists in ONS ASHE Table 14 and
//   SOC 2020 Volume 1.
// - socExt and socIndexTitles: exact job titles from the ONS SOC 2020 Volume 2 coding
//   index (version 14) that ONS itself codes to `soc`, and the extended sub-unit group
//   code for the first of them. This is the evidence for the SOC mapping.
// - apprenticeships: Skills England apprenticeship standard references. Each must be
//   "Approved for delivery" in the committed snapshot and must be named on the NCS
//   profile for the occupation, or list the occupation title or an alias among its
//   typical job titles, or have a title identical to the occupation title or an alias.
// - licences: ids from ./licences.ts. Each pairing needs evidence on the NCS profile,
//   in the ONS SOC 2020 entry-route text, or on the licence body's own page.
// - qualifications: named qualifications that appear on the occupation's NCS profile.
// - ncsProfile: a National Careers Service job profile slug that resolved on
//   28 September 2026 (the service is renamed "Get careers information and advice" on
//   1 October 2026; see README for how the URLs are recorded).
//
// WHAT IS EDITORIAL JUDGEMENT (not sourced data, and must never be presented as such):
// - title, aliases and description (written in our own words; ONS text is not copied)
// - skills and their importance (1 = useful, 5 = essential), mapped to ids in
//   src/data/skills-taxonomy.ts
// - degreeUsuallyRequired: whether a degree (including a degree apprenticeship at
//   level 6 or 7) is normally needed to get in. It is false wherever the ONS SOC 2020
//   entry-route text or the NCS profile documents a route below degree level, such as
//   a level 2 to 5 apprenticeship, an HND or college course, or working up from a
//   junior role. It says nothing about how many people in the job hold degrees.
// - audiences (which career changers the destination suits) and payNote
//
// Pay is never stored here. It comes from ./ashe.ts by SOC code, and it describes the
// whole unit group, not only the job title shown.

