export const CAREER_OCCUPATIONS: CareerOccupation[] = RAW.map((o) => ({
  ...o,
  aliases: o.aliases ?? [],
  skills: o.skills.map(([skillId, importance]) => ({ skillId, importance })),
  apprenticeships: o.apprenticeships ?? [],
  licences: o.licences ?? [],
  qualifications: o.qualifications ?? [],
}));

const BY_ID = new Map(CAREER_OCCUPATIONS.map((o) => [o.id, o]));

export function getCareerOccupation(id: string): CareerOccupation | undefined {
  return BY_ID.get(id);
}

/** All curated occupations that share a SOC 2020 unit group (and therefore share ASHE pay). */
export function getCareerOccupationsBySoc(soc: string): CareerOccupation[] {
  return CAREER_OCCUPATIONS.filter((o) => o.soc === soc);
}

export function getCareerOccupationsForAudience(audience: Audience): CareerOccupation[] {
  return CAREER_OCCUPATIONS.filter((o) => o.audiences.includes(audience));
}

/** Destinations that do not usually need a degree (an editorial flag, see file header). */
export function getNoDegreeOccupations(): CareerOccupation[] {
  return CAREER_OCCUPATIONS.filter((o) => !o.degreeUsuallyRequired);
}
